SELECT DATE '2024-01-15' AS date_literal;
SELECT TIMESTAMP '2024-01-15 10:30:00' AS timestamp_literal;
SELECT INTERVAL '1 day' AS interval_literal;

SELECT DATE '2024-01-15' + 7 AS date_plus_int;
SELECT DATE '2024-01-15' - 7 AS date_minus_int;
SELECT DATE '2024-01-15' - DATE '2024-01-01' AS date_diff;
SELECT DATE '2024-01-15' + INTERVAL '1 month' AS date_plus_interval;
SELECT TIMESTAMP '2024-01-15 10:30:00' + INTERVAL '2 hours' AS ts_plus_interval;

SELECT EXTRACT(YEAR FROM DATE '2024-06-15') AS year;
SELECT EXTRACT(MONTH FROM DATE '2024-06-15') AS month;
SELECT EXTRACT(DAY FROM DATE '2024-06-15') AS day;
SELECT EXTRACT(DOW FROM DATE '2024-06-15') AS dow;
SELECT EXTRACT(HOUR FROM TIMESTAMP '2024-01-15 14:30:45') AS hour;
SELECT EXTRACT(MINUTE FROM TIMESTAMP '2024-01-15 14:30:45') AS minute;
SELECT EXTRACT(SECOND FROM TIMESTAMP '2024-01-15 14:30:45') AS second;

SELECT DATE_TRUNC('year', TIMESTAMP '2024-06-15 14:30:45') AS trunc_year;
SELECT DATE_TRUNC('month', TIMESTAMP '2024-06-15 14:30:45') AS trunc_month;
SELECT DATE_TRUNC('day', TIMESTAMP '2024-06-15 14:30:45') AS trunc_day;
SELECT DATE_TRUNC('hour', TIMESTAMP '2024-06-15 14:30:45') AS trunc_hour;

SELECT TO_CHAR(DATE '2024-01-15', 'YYYY-MM-DD') AS formatted_date;
SELECT TO_CHAR(TIMESTAMP '2024-01-15 14:30:45', 'YYYY-MM-DD HH24:MI:SS') AS formatted_ts;

SELECT AGE(DATE '2024-06-15', DATE '2024-01-01') AS age_result;

SELECT DATE '2024-01-15' > DATE '2024-01-01' AS date_gt;
SELECT DATE '2024-01-15' < DATE '2024-01-01' AS date_lt;
SELECT DATE '2024-01-15' = DATE '2024-01-15' AS date_eq;

