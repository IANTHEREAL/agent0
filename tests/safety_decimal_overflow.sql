-- Safety regression tests for Decimal checked arithmetic (PR #2028).
-- P0 fix: rust_decimal v1.40 panicked on overflow for +, -, *, /, %.
-- Decimal::MAX = 79228162514264337593543950335 (96-bit, ~29 digits)

CREATE TABLE dec_overflow_test (id INT PRIMARY KEY, val NUMERIC);

-- ================================================================
-- Boundary: int32 MAX (2147483647) + 0 must succeed
-- ================================================================
SELECT 2147483647 + 0;

-- ================================================================
-- Boundary: int32 MAX + 1 must error (not wrap to -2147483648)
-- ================================================================
SELECT 2147483647 + 1;

-- ================================================================
-- Boundary: int32 MIN - 1 → parser promotes literal to bigint, so this
-- succeeds (not int32 overflow). Intentionally omitted.
-- ================================================================

-- ================================================================
-- Boundary: int64 MAX + 0 must succeed
-- ================================================================
SELECT 9223372036854775807::bigint + 0;

-- ================================================================
-- Boundary: int64 MAX + 1 must error
-- ================================================================
SELECT 9223372036854775807::bigint + 1;

-- ================================================================
-- Boundary: int64 MIN - 1 must error
-- ================================================================
SELECT (-9223372036854775808)::bigint - 1;

-- ================================================================
-- Boundary: Decimal::MAX exactly (no overflow)
-- ================================================================
SELECT 79228162514264337593543950335::numeric + 0;

-- ================================================================
-- Boundary: Decimal::MAX + 1 must overflow
-- ================================================================
SELECT 79228162514264337593543950335::numeric + 1;

-- ================================================================
-- Boundary: Decimal::MAX * 2 must overflow
-- ================================================================
SELECT 79228162514264337593543950335::numeric * 2;

-- ================================================================
-- Boundary: -Decimal::MAX - 1 (negative overflow)
-- ================================================================
SELECT (-79228162514264337593543950335)::numeric - 1;

-- ================================================================
-- Division by zero
-- ================================================================
SELECT 1::numeric / 0;

-- ================================================================
-- SUM: single MAX value (no overflow) then two MAX values (overflow)
-- ================================================================
INSERT INTO dec_overflow_test VALUES (1, 79228162514264337593543950335);
SELECT SUM(val) FROM dec_overflow_test;
INSERT INTO dec_overflow_test VALUES (2, 1);
SELECT SUM(val) FROM dec_overflow_test;

-- ================================================================
-- AVG: two MAX values (internal sum overflows)
-- ================================================================
DELETE FROM dec_overflow_test;
INSERT INTO dec_overflow_test VALUES (1, 79228162514264337593543950335);
INSERT INTO dec_overflow_test VALUES (2, 79228162514264337593543950335);
SELECT AVG(val) FROM dec_overflow_test;

-- ================================================================
-- exp() large argument
-- ================================================================
SELECT exp(1000::numeric);

-- ================================================================
-- Normal edge cases that must succeed
-- ================================================================
SELECT 1.5::numeric + 2.5::numeric;
SELECT 0::numeric / 1;
SELECT (-2147483648)::int + 0;

DROP TABLE dec_overflow_test;
